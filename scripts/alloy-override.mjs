// Web KI-039: Loki got no logs from this repo's backend stacks. The backend's Alloy (docker/alloy/config.alloy) keeps only the
// containers whose compose project label is exactly "ecomdemo" (one rule in each of its two pipelines), and this repo runs the
// stack as another project (`ecomdemo-backend-readonly`, the clone's folder), so Alloy dropped every line. Traces were fine.
//
// The fix is NOT a copy of the backend's file kept in this repo (it would drift from the pin). Each time scripts/backend-stack.sh
// runs, this reads the clone's own config.alloy, points the project rules at this stack's project, and writes the result to
// .local/ (ignored), which the stack mounts over Alloy's config. Anything it does not recognise fails the start loudly, so a
// backend change cannot turn the override into a silent no-op (Loki empty again, with no error).
//
//   node scripts/alloy-override.mjs <backend config.alloy> <compose project> <output file>
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectLabel = '__meta_docker_container_label_com_docker_compose_project'
// A project rule as the backend writes it: the label, then on the next line the regex it keeps (1: up to the value, 2: the value).
const projectRule = new RegExp(`(source_labels\\s*=\\s*\\["${projectLabel}"\\]\\s*\\n\\s*regex\\s*=\\s*)"([^"]*)"`, 'g')
// Compose's own rule for project names, so the name needs no escaping inside the RE2 regex or the Alloy string.
const projectName = /^[a-z0-9][a-z0-9_-]*$/

export function retargetAlloyConfig(config, project, source = 'docker/alloy/config.alloy') {
  if (!projectName.test(project)) {
    throw new Error(`alloy-override: ${JSON.stringify(project)} is not a compose project name`)
  }
  const mentions = config.split(projectLabel).length - 1
  const rules = [...config.matchAll(projectRule)]
  if (rules.length === 0 || rules.length !== mentions) {
    throw new Error(
      `alloy-override: expected every project rule in ${source} to be \`source_labels = ["${projectLabel}"]\` followed by ` +
        `\`regex = "..."\`; found ${rules.length} such rule(s) and ${mentions} mention(s) of the label. The backend's Alloy config ` +
        'changed: look at it before starting the stack (web KI-039).',
    )
  }
  const unexpected = rules.map((rule) => rule[2]).filter((value) => value !== 'ecomdemo')
  if (unexpected.length > 0) {
    throw new Error(
      `alloy-override: a project rule in ${source} keeps ${unexpected.map((value) => JSON.stringify(value)).join(', ')}, ` +
        'not "ecomdemo". The backend changed its project filter: look at it before starting the stack (web KI-039).',
    )
  }
  // Exactly this stack's project, as the backend's rule is exactly its own: Alloy here sees the whole Docker daemon, and the
  // backend team's stack (project "ecomdemo") on the same machine already ships to its own Loki.
  const retargeted = config.replace(projectRule, (_match, head) => `${head}"${project}"`)
  const header =
    `// GENERATED by EcomDemo-Web scripts/alloy-override.mjs from ${source}: the ${rules.length} compose project rules keep ` +
    `"${project}" instead of "ecomdemo" (web KI-039). Regenerated at every stack start; do not edit.\n`
  return header + retargeted
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [source, project, output] = process.argv.slice(2)
  if (!source || !project || !output) {
    console.error('usage: node scripts/alloy-override.mjs <backend config.alloy> <compose project> <output file>')
    process.exit(2)
  }
  try {
    const generated = retargetAlloyConfig(readFileSync(source, 'utf8'), project, source)
    mkdirSync(dirname(output), { recursive: true })
    // Rewritten only when it changes: a running Alloy has this file bind-mounted, and the same bytes need no write.
    let current = ''
    try {
      current = readFileSync(output, 'utf8')
    } catch {
      // Not written yet.
    }
    if (current !== generated) writeFileSync(output, generated)
    console.error(`alloy-override: Alloy keeps the compose project "${project}" (${output})`)
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  }
}
